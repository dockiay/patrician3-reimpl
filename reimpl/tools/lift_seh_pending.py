#!/usr/bin/env python3
"""Reproduce the two remaining SEH ports; signatures and native CRT calls are explicit.

Run with --binary EXE from the repository root. No exception handlers are executed.
"""
import argparse
import json
from pathlib import Path
from lift import Lifter

ROOT = Path(__file__).resolve().parents[2]
NATIVE = {0x639F20, 0x63A6A0, 0x63A6E0, 0x63C610, 0x639C28}


class PendingLifter(Lifter):
    def call_info(self, target, insn, instructions, index):
        if target == 0x64DF80:
            return {0x511338: 3, 0x52CEA4: 8, 0x52CEE6: 7, 0x52D02B: 11}[insn.address], False
        if target in (0x64F7B9, 0x64F7E2):
            return 1, False
        if target == 0x639F20:
            return 3, False
        if target == 0x52DE40:
            return 2, False
        if target in (0x63A6A0, 0x63A6E0):
            return 4, True
        if target in (0x63C610, 0x639C28):
            return 0, False
        return super().call_info(target, insn, instructions, index)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--binary', required=True)
    args = ap.parse_args()
    lifter = PendingLifter(args.binary, str(ROOT / 'research/catalog/functions.tsv'))
    source = [
        '//! Generated by reimpl/tools/lift_seh_pending.py; regenerate instead of editing.',
        '#![allow(unused_mut, unused_variables, unused_assignments, clippy::all)]',
        'use crate::economy::ops_misc::OpsHost;',
        'use crate::flatmem::Mem;',
        'use crate::x86rt::*;',
    ]
    specs = []
    for address in (0x511270, 0x52C6C0):
        row = lifter.cat[address]
        code, spec = lifter.lift(address, int(row['bytes']), row['name'])
        for target in NATIVE:
            # The caller's push/cleanup remain in the generated code. Native CRT
            # returns may change EDX/x87 as well as EAX, so they cannot use OpsHost.
            import re
            code = re.sub(
                rf'\{{ let args = \[[^\n]*\]; c.r\[0\] = host.call\(m, {target:#x}, c.r\[1\], &args\); \}}',
                f'crate::economy::seh_pending::native(&mut c, m, {target:#x});', code)
        source.append(code)
        specs.append(spec)
    (ROOT / 'reimpl/p3-core/src/lifted/seh_pending.rs').write_text('\n\n'.join(source) + '\n', encoding='utf-8')
    (ROOT / 'reimpl/oracle/seh_pending_signatures.json').write_text(json.dumps(specs, indent=2) + '\n', encoding='utf-8')
    print('Two functions generated; stack depths verified.')


if __name__ == '__main__':
    main()
