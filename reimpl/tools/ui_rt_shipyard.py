"""Regenerate the shipyard sidebar draw routine for the UI runtime."""
import argparse
import os
from pathlib import Path
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "p3-mvp/src/ui_rt/shipyard_lifted.rs"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", required=True)
    parser.add_argument("--catalog", default=str(ROOT.parent / "research/catalog/functions.tsv"))
    args = parser.parse_args()
    with tempfile.TemporaryDirectory() as temporary:
        generated = Path(temporary) / "shipyard.rs"
        subprocess.run([
            sys.executable, str(ROOT / "tools/lift.py"), "--binary", args.binary,
            "--catalog", args.catalog, "--ext", "--lax", "--fpu-exit",
            "--out", str(generated), "--spec", str(Path(temporary) / "spec.json"), "0x005AD140",
        ], check=True, env={**os.environ, "PYTHONUTF8": "1"})
        source = generated.read_text(encoding="utf-8")
    assert "pub fn shipyard_side_menu_draw(" in source
    source = source.replace("use crate::economy::", "use p3_core::economy::")
    source = source.replace("use crate::flatmem::", "use p3_core::flatmem::")
    source = source.replace("use crate::x86rt::", "use p3_core::x86rt::")
    source = source[source.index("#![allow"):]
    header = (
        "//! Generated by reimpl/tools/ui_rt_shipyard.py; do not edit by hand.\n"
        "//! Keeps the original cdecl stack cleanup in 0x005AD140. The older J08\n"
        "//! translation popped DrawText arguments early and corrupted the caller's render destination.\n"
    )
    table = "\npub static SHIPYARD: [(u32, super::core_table::CoreFn); 1] = [(0x005A_D140, shipyard_side_menu_draw)];\n"
    OUT.write_text(header + source + table, encoding="utf-8")
    print(OUT)


if __name__ == "__main__":
    main()
