"""Generate missing native UI Hanse-office functions from the local English EXE."""
import argparse
import csv
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile

os.environ['PYTHONUTF8'] = '1'
ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT.parent / 'research/catalog/functions.tsv'
OUT = ROOT / 'p3-mvp/src/ui_rt/hanse_lifted.rs'
SEEDS = [0x4F8560, 0x4DA510, 0x4DAA50, 0x4DA860, 0x53A010, 0x53A0B0, 0x53A170, 0x4D9000, 0x53FCA0, 0x4D7B10]

def main():
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument('--binary', required=True)
    args = parser.parse_args()
    names = {int(row['address'], 16): row['name'] for row in csv.DictReader(CATALOG.open(encoding='utf-8'), delimiter='\t')}
    bodies, rows = [], []
    with tempfile.TemporaryDirectory() as tmp:
        src, spec = Path(tmp)/'hanse.rs', Path(tmp)/'hanse.json'
        for address in SEEDS:
            subprocess.run([sys.executable, str(ROOT/'tools/lift.py'), '--binary', args.binary,
                '--catalog', str(CATALOG), '--lax', '--ext', '--fpu-exit', '--out', str(src),
                '--spec', str(spec), hex(address)], check=True, capture_output=True)
            report = json.loads(spec.read_text(encoding='utf-8'))
            if report['unsupported']:
                raise SystemExit(report['unsupported'])
            body = src.read_text(encoding='utf-8').split('\npub fn call_by_name')[0]
            body = re.split(r'(?m)^(?=pub fn )', body)[1]
            body = re.sub(r'^pub fn \w+\(', f'pub fn f_{address:08x}(', body, count=1)
            body = re.sub(r'c\.push\(m,(rm\(m,[^;]*?\))\);', r'{ let v = \1; c.push(m, v); }', body)
            # Auxiliares CRT que devuelven EDX:EAX (`__allmul`/`__alldiv`, `__allshr`, `_ftol`): no pueden pasar por OpsHost (solo EAX).
            for native in (0x63a6a0, 0x63a6e0, 0x63c610, 0x639c28):
                body = re.sub(rf"\{{ let args = \[[^\n]*\]; c.r\[0\] = host.call\(m, {native:#x}, c.r\[1\], &args\); \}}",
                              f"p3_core::economy::seh_pending::native(&mut c, m, {native:#x});", body)
            bodies.append(f'/// `{names[address]}` (`{address:#010x}`).\n'+body)
            rows.append(address)
    head = ['//! Generated by `tools/ui_rt_hanse.py`; do not edit by hand.',
        '#![allow(unused_mut, unused_variables, unused_assignments, non_snake_case, clippy::all)]',
        'use p3_core::economy::ops_misc::OpsHost;', 'use p3_core::flatmem::Mem;', 'use p3_core::x86rt::*;',
        f'pub static HANSE: [(u32, super::core_table::CoreFn); {len(rows)}] = [']
    head += [f'    ({f:#x}, f_{f:08x}),' for f in rows] + ['];', '']
    OUT.write_text('\n'.join(head)+''.join(bodies), encoding='utf-8')
    print(f'{len(rows)} Hanse-office functions generated')

if __name__ == '__main__':
    main()
