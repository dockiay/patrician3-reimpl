"""Generate missing native UI ship-order functions from the local English EXE."""
import argparse
import csv
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile

os.environ['PYTHONUTF8'] = '1'
ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT.parent / 'research/catalog/functions.tsv'
OUT = ROOT / 'p3-mvp/src/ui_rt/ship_orders_lifted.rs'
SEEDS = [0x447580, 0x448D80, 0x45B9C0, 0x45BCF0, 0x45BDC0, 0x4F5900, 0x4F9050, 0x505290, 0x517770, 0x519D90, 0x537C20, 0x537DD0, 0x5184F0, 0x4F6BD0, 0x52A360, 0x52AFC0, 0x52B0D0, 0x4F9120, 0x52B110, 0x52B670, 0x508660, 0x53CAF0, 0x538210, 0x53D6D0, 0x489B80]

def main():
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument('--binary', required=True)
    parser.add_argument('--only', default='', help='Regenerate selected hex addresses, preserving other handlers')
    args = parser.parse_args()
    names = {int(row['address'], 16): row['name'] for row in csv.DictReader(CATALOG.open(encoding='utf-8'), delimiter='\t')}
    only = {int(a, 16) for a in args.only.split(',') if a}
    if only - set(SEEDS):
        raise SystemExit('Selected address is not a ship-order seed')
    overrides = {}
    for line in (ROOT/'tools/ui_rt_fix.sites').read_text(encoding='utf-8').splitlines():
        if line and not line.startswith('#'):
            caller, ret, count = line.split()
            overrides.setdefault(names[int(caller, 16)], {})[str(int(ret, 16))] = int(count)
    bodies, rows = [], []
    with tempfile.TemporaryDirectory() as tmp:
        src, spec = Path(tmp)/'orders.rs', Path(tmp)/'orders.json'
        nover = Path(tmp)/'overrides.json'
        nover.write_text(json.dumps(overrides), encoding='utf-8')
        for address in SEEDS:
            if only and address not in only:
                continue
            subprocess.run([sys.executable, str(ROOT/'tools/lift.py'), '--binary', args.binary,
                '--catalog', str(CATALOG), '--lax', '--ext', '--fpu-exit', '--out', str(src),
                '--nover', str(nover), '--spec', str(spec), hex(address)], check=True, capture_output=True)
            report = json.loads(spec.read_text(encoding='utf-8'))
            if report['unsupported']:
                raise SystemExit(report['unsupported'])
            body = src.read_text(encoding='utf-8').split('\npub fn call_by_name')[0]
            body = re.split(r'(?m)^(?=pub fn )', body)[1]
            body = re.sub(r'^pub fn \w+\(', f'pub fn f_{address:08x}(', body, count=1)
            body = re.sub(r'c\.push\(m,(rm\(m,[^;]*?\))\);', r'{ let v = \1; c.push(m, v); }', body)
            bodies.append(f'/// `{names[address]}` (`{address:#010x}`).\n'+body)
            rows.append(address)
    if only:
        previous = OUT.read_text(encoding='utf-8')
        pattern = r'(?ms)^/// `\w+` \(`(0x[0-9a-f]{8})`\)\.\n.*?(?=^/// `\w+` \(`0x[0-9a-f]{8}`\)\.\n|\Z)'
        kept = {int(m[1], 16): m[0] for m in re.finditer(pattern, previous)}
        if set(kept) != set(SEEDS):
            raise SystemExit('Cannot preserve existing ship-order handlers')
        kept.update(zip(rows, bodies))
        rows = list(SEEDS)
        bodies = [kept[a] for a in rows]
    head = ['//! Generated by `tools/ui_rt_ship_orders.py`; do not edit by hand.',
        '#![allow(unused_mut, unused_variables, unused_assignments, non_snake_case, clippy::all)]',
        'use p3_core::economy::ops_misc::OpsHost;', 'use p3_core::flatmem::Mem;', 'use p3_core::x86rt::*;',
        f'pub static SHIP_ORDERS: [(u32, super::core_table::CoreFn); {len(rows)}] = [']
    head += [f'    ({f:#x}, f_{f:08x}),' for f in rows] + ['];', '']
    OUT.write_text('\n'.join(head)+''.join(bodies), encoding='utf-8')
    print(f'{len(rows)} ship-order functions generated')

if __name__ == '__main__':
    main()
