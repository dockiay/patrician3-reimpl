//! (`game_screen_on_key_down` 0x4247A0, `virtual_key_to_ascii` 0x4C0F50…).
use p3_mvp::ui_rt::win32::*;
use winit::keyboard::KeyCode as K;

pub fn vk(code: K) -> Option<u8> {
    let letter = |c: u8| Some(c);
    Some(match code {
        K::KeyA => return letter(b'A'),
        K::KeyB => return letter(b'B'),
        K::KeyC => return letter(b'C'),
        K::KeyD => return letter(b'D'),
        K::KeyE => return letter(b'E'),
        K::KeyF => return letter(b'F'),
        K::KeyG => return letter(b'G'),
        K::KeyH => return letter(b'H'),
        K::KeyI => return letter(b'I'),
        K::KeyJ => return letter(b'J'),
        K::KeyK => return letter(b'K'),
        K::KeyL => return letter(b'L'),
        K::KeyM => return letter(b'M'),
        K::KeyN => return letter(b'N'),
        K::KeyO => return letter(b'O'),
        K::KeyP => return letter(b'P'),
        K::KeyQ => return letter(b'Q'),
        K::KeyR => return letter(b'R'),
        K::KeyS => return letter(b'S'),
        K::KeyT => return letter(b'T'),
        K::KeyU => return letter(b'U'),
        K::KeyV => return letter(b'V'),
        K::KeyW => return letter(b'W'),
        K::KeyX => return letter(b'X'),
        K::KeyY => return letter(b'Y'),
        K::KeyZ => return letter(b'Z'),
        K::Digit0 => b'0',
        K::Digit1 => b'1',
        K::Digit2 => b'2',
        K::Digit3 => b'3',
        K::Digit4 => b'4',
        K::Digit5 => b'5',
        K::Digit6 => b'6',
        K::Digit7 => b'7',
        K::Digit8 => b'8',
        K::Digit9 => b'9',
        K::Numpad0 => VK_NUMPAD0,
        K::Numpad1 => VK_NUMPAD0 + 1,
        K::Numpad2 => VK_NUMPAD0 + 2,
        K::Numpad3 => VK_NUMPAD0 + 3,
        K::Numpad4 => VK_NUMPAD0 + 4,
        K::Numpad5 => VK_NUMPAD0 + 5,
        K::Numpad6 => VK_NUMPAD0 + 6,
        K::Numpad7 => VK_NUMPAD0 + 7,
        K::Numpad8 => VK_NUMPAD0 + 8,
        K::Numpad9 => VK_NUMPAD0 + 9,
        K::NumpadMultiply => VK_MULTIPLY,
        K::NumpadAdd => VK_ADD,
        K::NumpadSubtract => VK_SUBTRACT,
        K::NumpadDecimal => VK_DECIMAL,
        K::NumpadDivide => VK_DIVIDE,
        K::NumpadEnter | K::Enter => VK_RETURN,
        K::Escape => VK_ESCAPE,
        K::Backspace => VK_BACK,
        K::Tab => VK_TAB,
        K::Space => VK_SPACE,
        K::ShiftLeft => VK_LSHIFT,
        K::ShiftRight => VK_RSHIFT,
        K::ControlLeft => VK_LCONTROL,
        K::ControlRight => VK_RCONTROL,
        K::AltLeft => VK_LMENU,
        K::AltRight => VK_RMENU,
        K::Pause => VK_PAUSE,
        K::CapsLock => VK_CAPITAL,
        K::NumLock => VK_NUMLOCK,
        K::ScrollLock => VK_SCROLL,
        K::PageUp => VK_PRIOR,
        K::PageDown => VK_NEXT,
        K::End => VK_END,
        K::Home => VK_HOME,
        K::ArrowLeft => VK_LEFT,
        K::ArrowUp => VK_UP,
        K::ArrowRight => VK_RIGHT,
        K::ArrowDown => VK_DOWN,
        K::PrintScreen => VK_SNAPSHOT,
        K::Insert => VK_INSERT,
        K::Delete => VK_DELETE,
        K::Equal => VK_OEM_PLUS,
        K::Minus => VK_OEM_MINUS,
        K::Comma => VK_OEM_COMMA,
        K::Period => VK_OEM_PERIOD,
        K::F1 => VK_F1,
        K::F2 => VK_F1 + 1,
        K::F3 => VK_F1 + 2,
        K::F4 => VK_F1 + 3,
        K::F5 => VK_F1 + 4,
        K::F6 => VK_F1 + 5,
        K::F7 => VK_F1 + 6,
        K::F8 => VK_F1 + 7,
        K::F9 => VK_F1 + 8,
        K::F10 => VK_F1 + 9,
        K::F11 => VK_F1 + 10,
        K::F12 => VK_F1 + 11,
        _ => return None,
    })
}

/// Texto de una pulsación en la página de códigos del juego (Windows-1252; los caracteres de fuera se descartan).
pub fn cp1252(text: &str) -> Vec<u8> {
    text.chars()
        .filter_map(|c| {
            let u = c as u32;
            match u {
                0..=0x7F | 0xA0..=0xFF => Some(u as u8),
                0x20AC => Some(0x80),
                0x201A => Some(0x82),
                0x201E => Some(0x84),
                0x2026 => Some(0x85),
                0x2018 => Some(0x91),
                0x2019 => Some(0x92),
                0x201C => Some(0x93),
                0x201D => Some(0x94),
                0x2013 => Some(0x96),
                0x2014 => Some(0x97),
                _ => None,
            }
        })
        .collect()
}
